// Builds hooks/guide.js, the text of the guide shown by /sapp-help, from the one
// source of truth: skills/sapp-ai-guide/SKILL.md.
//
//   node plugins/sapp-mod/scripts/build-guide.mjs
//
// A mod cannot read files at run time, so the guide is copied into a module here.
// The skill and the /sapp-help card are the same text; a test fails when they drift.
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath, pathToFileURL } from 'node:url'

const here = new URL('../', import.meta.url)
export const SKILL_PATH = 'skills/sapp-ai-guide/SKILL.md'
export const GUIDE_OUT = 'hooks/guide.js'

// Splits a SKILL.md into its frontmatter fields (flat `key: value` lines) and its body.
export function parseSkill(text) {
  const match = /^---\n([\s\S]*?)\n---\n([\s\S]*)$/.exec(text)
  if (!match) throw new Error('SKILL.md has no frontmatter')
  const fields = {}
  for (const line of match[1].split('\n')) {
    const at = line.indexOf(':')
    if (at < 1) throw new Error(`bad frontmatter line: ${line}`)
    fields[line.slice(0, at).trim()] = line.slice(at + 1).trim()
  }
  return { fields, body: match[2].trim() }
}

export function readSkill() {
  return parseSkill(readFileSync(new URL(SKILL_PATH, here), 'utf8'))
}

// With no argument, the committed SKILL.md; a test passes its own text.
export function buildGuideModule(skillText) {
  const { body } = skillText === undefined ? readSkill() : parseSkill(skillText)
  return (
    `// Generated by scripts/build-guide.mjs from ${SKILL_PATH}. Do not edit by hand:\n` +
    '// edit the SKILL.md, run `npm run build:guide` and commit the result.\n' +
    `export const GUIDE_MARKDOWN = ${JSON.stringify(body)}\n`
  )
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const out = fileURLToPath(new URL(GUIDE_OUT, here))
  const source = buildGuideModule()
  writeFileSync(out, source)
  console.log(`wrote ${out} (${source.length} characters)`)
}
